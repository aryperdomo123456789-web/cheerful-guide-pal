export function isLanguage(value: string | null | undefined): value is LanguageCode {
  return LANGUAGES.some((l) => l.code === value);
}

export function translate(
  language: string | null | undefined,
  key: TranslationKey,
  vars?: Record<string, string | number>,
) {
  const lang: LanguageCode = isLanguage(language) ? language : DEFAULT_LANGUAGE;
  const raw = DICTS[lang][key] ?? DICTS[DEFAULT_LANGUAGE][key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    raw,
  );
}

